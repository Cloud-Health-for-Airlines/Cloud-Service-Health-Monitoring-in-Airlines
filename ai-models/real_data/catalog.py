"""Catalog of the real, public datasets BACCP is grounded in.

Every entry is a dataset that a reviewer can download themselves, with its
provenance, licence/citation and the exact role it plays in the pipeline.
Nothing in this catalog is generated by an AI model or by our own simulator.

Roles (how each dataset is used):

- airline_ops      : real flight schedules, delays and cancellations (BTS On-Time).
                     Drives *when* airline traffic happens and supplies real
                     ground-truth disruption days (Southwest Dec-2022, Delta Jul-2024).
- airline_booking  : real ticket / passenger volumes per market (BTS DB1B).
                     Drives *how many* reservations each flight generates.
- cloud_workload   : real request-arrival traces from a production cloud
                     (Azure Functions 2019). Drives minute-level burstiness.
- cluster_workload : real CPU / memory utilisation of production clusters and
                     microservices (Alibaba 2022 microservices, Google Borg).
                     Drives how the cloud tier provisions and saturates.
- cloud_health     : real public cloud incident history (Google Cloud Service
                     Health). Drives realistic fault frequency / duration.
- microservice_rca : labelled failure cases on real microservice benchmarks
                     (RCAEval incl. Train-Ticket). Used for external validation.
"""

